-- Jalankan di Supabase Dashboard > SQL Editor (setelah auth.sql)
-- Modul pengabdian: strukturnya sama dengan penelitian
-- (kategori, subkategori, ketua/ketua luar, anggota tim, penginput, hak akses per role)

-- ============================================================
-- 1. Tabel
-- ============================================================
create table if not exists public.kategori_pengabdian (
  id bigint generated by default as identity primary key,
  kategori_pengabdian text not null
);

create table if not exists public.subkategori_pengabdian (
  id bigint generated by default as identity primary key,
  sub_kategori_pengabdian text not null,
  kategori_pengabdian_id bigint not null
    references public.kategori_pengabdian (id) on update cascade on delete restrict
);

create table if not exists public.pengabdian (
  id bigint generated by default as identity primary key,
  -- ketua: salah satu dari dosen_id (daftar dosen) atau ketua_luar (nama bebas)
  dosen_id bigint references public.dosen (id) on update cascade on delete restrict,
  ketua_luar text,
  sub_kategori_pengabdian_id bigint not null
    references public.subkategori_pengabdian (id) on update cascade on delete restrict,
  judul_pengabdian text not null,
  tahun smallint not null check (tahun between 1900 and 2100),
  publikasi text,
  url_bukti text,
  url_dokumen text,
  keterangan text,
  created_by uuid default auth.uid() references auth.users (id) on delete set null,
  constraint pengabdian_ketua_check check (num_nonnulls(dosen_id, ketua_luar) = 1)
);

create table if not exists public.pengabdian_anggota (
  pengabdian_id bigint not null references public.pengabdian (id) on delete cascade,
  dosen_id bigint not null references public.dosen (id) on delete restrict,
  primary key (pengabdian_id, dosen_id)
);

create index if not exists subkategori_pengabdian_kategori_idx
  on public.subkategori_pengabdian (kategori_pengabdian_id);
create index if not exists pengabdian_dosen_idx on public.pengabdian (dosen_id);
create index if not exists pengabdian_subkategori_idx
  on public.pengabdian (sub_kategori_pengabdian_id);
create index if not exists pengabdian_anggota_dosen_idx on public.pengabdian_anggota (dosen_id);

-- ============================================================
-- 2. Fungsi bantu (lihat auth.sql untuk my_role, my_dosen_id, is_admin)
-- ============================================================
create or replace function public.is_anggota_pengabdian(pid bigint)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.pengabdian_anggota
    where pengabdian_id = pid and dosen_id = public.my_dosen_id()
  );
$$;

create or replace function public.is_ketua_pengabdian(pid bigint)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.pengabdian
    where id = pid and dosen_id = public.my_dosen_id()
  );
$$;

create or replace function public.is_pembuat_pengabdian(pid bigint)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.pengabdian
    where id = pid and created_by = auth.uid()
  );
$$;

create or replace function public.can_view_pengabdian(pid bigint)
returns boolean language sql stable security definer set search_path = '' as $$
  select coalesce(public.my_role() in ('admin', 'pemantau'), false)
    or public.is_ketua_pengabdian(pid)
    or public.is_anggota_pengabdian(pid)
    or public.is_pembuat_pengabdian(pid);
$$;

-- ============================================================
-- 3. Hak akses (RLS)
-- ============================================================
alter table public.kategori_pengabdian enable row level security;
alter table public.subkategori_pengabdian enable row level security;
alter table public.pengabdian enable row level security;
alter table public.pengabdian_anggota enable row level security;

-- Kategori & subkategori: semua user login membaca, hanya admin yang mengubah
create policy "baca kategori_pengabdian" on public.kategori_pengabdian
  for select to authenticated using (true);
create policy "admin kelola kategori_pengabdian" on public.kategori_pengabdian
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

create policy "baca subkategori_pengabdian" on public.subkategori_pengabdian
  for select to authenticated using (true);
create policy "admin kelola subkategori_pengabdian" on public.subkategori_pengabdian
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- Pengabdian
--   lihat     : admin & pemantau semua; dosen sebagai ketua, penginput, atau anggota
--   tambah    : admin, atau dosen (tercatat sebagai penginput)
--   ubah/hapus: admin, ketua, atau penginput
create policy "lihat pengabdian" on public.pengabdian
  for select to authenticated using (
    coalesce(public.my_role() in ('admin', 'pemantau'), false)
    or dosen_id = public.my_dosen_id()
    or created_by = auth.uid()
    or public.is_anggota_pengabdian(id)
  );

create policy "tambah pengabdian" on public.pengabdian
  for insert to authenticated
  with check (
    public.is_admin()
    or (public.my_role() = 'dosen' and created_by = auth.uid())
  );

create policy "ubah pengabdian" on public.pengabdian
  for update to authenticated
  using (public.is_admin() or dosen_id = public.my_dosen_id() or created_by = auth.uid())
  with check (public.is_admin() or dosen_id = public.my_dosen_id() or created_by = auth.uid());

create policy "hapus pengabdian" on public.pengabdian
  for delete to authenticated
  using (public.is_admin() or dosen_id = public.my_dosen_id() or created_by = auth.uid());

-- Anggota
create policy "lihat anggota pengabdian" on public.pengabdian_anggota
  for select to authenticated using (public.can_view_pengabdian(pengabdian_id));

create policy "kelola anggota pengabdian" on public.pengabdian_anggota
  for all to authenticated
  using (
    public.is_admin()
    or public.is_ketua_pengabdian(pengabdian_id)
    or public.is_pembuat_pengabdian(pengabdian_id)
  )
  with check (
    public.is_admin()
    or public.is_ketua_pengabdian(pengabdian_id)
    or public.is_pembuat_pengabdian(pengabdian_id)
  );
