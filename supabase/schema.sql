-- Jalankan di Supabase Dashboard > SQL Editor

create table if not exists public.prodi (
  id bigint generated by default as identity primary key,
  prodi text not null
);

create table if not exists public.dosen (
  id bigint generated by default as identity primary key,
  nama text not null,
  nidn varchar(20) not null unique,
  prodi_id bigint references public.prodi (id) on update cascade on delete restrict
);

create index if not exists dosen_prodi_id_idx on public.dosen (prodi_id);

-- Row Level Security: izinkan akses publik dengan anon key.
-- Untuk produksi, batasi ke pengguna yang login (auth.role() = 'authenticated').
alter table public.prodi enable row level security;
alter table public.dosen enable row level security;

create policy "akses publik prodi" on public.prodi
  for all using (true) with check (true);

create policy "akses publik dosen" on public.dosen
  for all using (true) with check (true);

-- Contoh data
insert into public.prodi (prodi) values
  ('Teknik Informatika'),
  ('Sistem Informasi');
