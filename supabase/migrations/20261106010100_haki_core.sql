-- 3. Helper akses (security definer; dipakai RLS dan RPC)
-- ============================================================
-- pemilik atau operator yang unitnya mencakup dokumen
create or replace function public.hki_owner_like(p_owner bigint, p_unit bigint)
returns boolean language sql stable security definer set search_path = '' as $$
  select coalesce(p_owner = public.my_dosen_id(), false)
    or (public.my_role() = 'operator' and public.my_unit_id() is not null
        and public.unit_in_scope(p_unit, public.my_unit_id()));
$$;

-- validator berwenang atas unit (unit validator null = seluruh institusi)
create or replace function public.hki_validator_for(p_unit bigint)
returns boolean language sql stable security definer set search_path = '' as $$
  select coalesce(public.my_role() = 'validator', false)
    and public.unit_in_scope(p_unit, public.my_unit_id());
$$;

create or replace function public.hki_is_confirmed_person(p_record uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.hki_persons
    where record_id = p_record and dosen_id = public.my_dosen_id() and status_cocok = 'dikonfirmasi'
  );
$$;

-- admin TIDAK otomatis melihat dokumen (keputusan D5)
create or replace function public.hki_can_view(p_record uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.hki_records r
    where r.id = p_record and r.deleted_at is null and (
      public.hki_owner_like(r.owner_dosen_id, r.unit_id)
      or public.hki_validator_for(r.unit_id)
      or (public.my_role() = 'pemantau' and r.workflow_status = 'ARCHIVED')
      or public.hki_is_confirmed_person(r.id)
    )
  );
$$;

create or replace function public.hki_can_edit(p_record uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.hki_records r
    where r.id = p_record and r.deleted_at is null and (
      (public.hki_owner_like(r.owner_dosen_id, r.unit_id) and r.workflow_status in
        ('DRAFT', 'NEEDS_VERIFICATION', 'NEEDS_REVISION', 'EXTRACTION_FAILED', 'CORRECTION_REQUESTED'))
      or (public.hki_validator_for(r.unit_id) and r.workflow_status in ('SUBMITTED', 'CORRECTION_REQUESTED'))
    )
  );
$$;

-- 'records/<uuid>/...' → uuid; null bila tidak valid
create or replace function public.hki_path_record(p_name text)
returns uuid language plpgsql immutable set search_path = '' as $$
begin
  if split_part(p_name, '/', 1) <> 'records' then
    return null;
  end if;
  return split_part(p_name, '/', 2)::uuid;
exception when others then
  return null;
end;
$$;

