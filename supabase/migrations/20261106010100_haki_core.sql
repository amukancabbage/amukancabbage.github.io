create table if not exists public.hki_records (
  id uuid primary key default gen_random_uuid(),
  jenis text check (jenis in ('hak_cipta', 'paten', 'paten_sederhana', 'merek', 'desain_industri',
                              'dtlst', 'rahasia_dagang', 'indikasi_geografis', 'pvt')),
  judul text,
  no_permohonan text,
  tgl_permohonan date,
  no_sertifikat text,
  status_hki text check (status_hki in ('permohonan', 'terdaftar', 'ditolak', 'ditarik', 'kedaluwarsa')),
  berlaku_mulai date,
  berlaku_akhir date,
  sumber_dana text,
  kegiatan_terkait text,
  pdki_url text,
  unit_id bigint references public.units (id) on delete set null,
  owner_dosen_id bigint not null references public.dosen (id) on delete restrict,
  created_by uuid references auth.users (id) on delete set null default auth.uid(),
  workflow_status text not null default 'DRAFT' check (workflow_status in (
    'DRAFT', 'EXTRACTING', 'EXTRACTION_FAILED', 'NEEDS_VERIFICATION', 'SUBMITTED',
    'NEEDS_REVISION', 'REJECTED', 'ARCHIVED', 'CORRECTION_REQUESTED')),
  extra jsonb not null default '{}'::jsonb,
  versi integer not null default 1,
  locked boolean not null default false,
  reread_count integer not null default 0,
  submitted_at timestamptz,
  validated_by uuid references auth.users (id) on delete set null,
  validated_at timestamptz,
  deleted_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists hki_records_owner_idx on public.hki_records (owner_dosen_id) where deleted_at is null;
create index if not exists hki_records_unit_idx on public.hki_records (unit_id) where deleted_at is null;
create index if not exists hki_records_status_idx on public.hki_records (workflow_status) where deleted_at is null;
-- nomor sertifikat unik hanya di arsip aktif, per jenis
create unique index if not exists hki_records_arsip_uq on public.hki_records (
  jenis, upper(regexp_replace(no_sertifikat, '[\s./-]+', '', 'g'))
) where workflow_status = 'ARCHIVED' and deleted_at is null and coalesce(no_sertifikat, '') <> '';

create table if not exists public.hki_persons (
  id bigint generated by default as identity primary key,
  record_id uuid not null references public.hki_records (id) on delete cascade,
  urutan integer not null default 0,
  nama text not null,
  nama_normal text not null default '',
  peran text not null default 'pencipta' check (peran in ('pencipta', 'pemegang', 'kuasa')),
  alamat text,
  kewarganegaraan text,
  dosen_id bigint references public.dosen (id) on delete set null,
  status_cocok text not null default 'eksternal'
    check (status_cocok in ('disarankan', 'dikonfirmasi', 'ditolak', 'eksternal', 'ambigu')),
  link_manual boolean not null default false,
  confidence numeric,
  page integer,
  evidence text,
  notified_at timestamptz
);
create index if not exists hki_persons_record_idx on public.hki_persons (record_id);
create index if not exists hki_persons_dosen_idx on public.hki_persons (dosen_id, status_cocok);

create table if not exists public.hki_files (
  id uuid primary key default gen_random_uuid(),
  record_id uuid not null references public.hki_records (id) on delete cascade,
  jenis text not null default 'lampiran' check (jenis in ('utama', 'lampiran')),
  storage_path text not null unique,
  nama_asli text not null,
  mime text not null,
  ukuran bigint not null,
  sha256 text not null,
  halaman integer,
  prep jsonb not null default '{}'::jsonb,
  uploaded_by uuid references auth.users (id) on delete set null default auth.uid(),
  created_at timestamptz not null default now()
);
create index if not exists hki_files_record_idx on public.hki_files (record_id);
create index if not exists hki_files_sha_idx on public.hki_files (sha256);
create unique index if not exists hki_files_utama_uq on public.hki_files (record_id) where jenis = 'utama';

create table if not exists public.hki_field_values (
  record_id uuid not null references public.hki_records (id) on delete cascade,
  field text not null,
  nilai_ai text,
  nilai_final text,
  confidence numeric,
  page integer,
  evidence text,
  dikonfirmasi boolean not null default false,
  diubah boolean not null default false,
  updated_at timestamptz not null default now(),
  primary key (record_id, field)
);

create table if not exists public.hki_extraction_jobs (
  id bigint generated by default as identity primary key,
  record_id uuid references public.hki_records (id) on delete cascade,
  file_id uuid references public.hki_files (id) on delete set null,
  tahap text not null check (tahap in ('classify', 'extract', 'escalate', 'cache')),
  model text,
  status text not null check (status in ('ok', 'gagal')),
  kode_error text,
  token_in integer,
  token_out integer,
  biaya numeric not null default 0,
  durasi_ms integer,
  prompt_version text,
  schema_version text,
  sha256 text,
  mock boolean not null default false,
  keluaran_mentah jsonb,
  created_at timestamptz not null default now()
);
create index if not exists hki_jobs_sha_idx on public.hki_extraction_jobs (sha256, status);
create index if not exists hki_jobs_created_idx on public.hki_extraction_jobs (created_at);

create table if not exists public.hki_review_actions (
  id bigint generated by default as identity primary key,
  record_id uuid not null references public.hki_records (id) on delete cascade,
  aksi text not null check (aksi in ('ajukan', 'approve', 'request_revision', 'reject', 'minta_koreksi')),
  catatan text,
  catatan_field jsonb,
  actor uuid references auth.users (id) on delete set null default auth.uid(),
  created_at timestamptz not null default now()
);
create index if not exists hki_review_record_idx on public.hki_review_actions (record_id);

create table if not exists public.hki_record_versions (
  id bigint generated by default as identity primary key,
  record_id uuid not null references public.hki_records (id) on delete cascade,
  versi integer not null,
  alasan text,
  snapshot jsonb not null,
  created_by uuid references auth.users (id) on delete set null default auth.uid(),
  created_at timestamptz not null default now(),
  unique (record_id, versi)
);

create table if not exists public.hki_person_rejections (
  id bigint generated by default as identity primary key,
  record_id uuid not null references public.hki_records (id) on delete cascade,
