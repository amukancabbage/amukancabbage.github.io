-- 6. View daftar (RLS tetap berlaku lewat security_invoker)
-- ============================================================
create or replace view public.hki_record_list with (security_invoker = true) as
select
  r.id, r.jenis, r.judul, r.no_permohonan, r.tgl_permohonan, r.no_sertifikat, r.status_hki,
  r.berlaku_mulai, r.berlaku_akhir, r.sumber_dana, r.kegiatan_terkait, r.pdki_url,
  r.unit_id, r.owner_dosen_id, r.created_by, r.workflow_status, r.versi, r.locked,
  r.submitted_at, r.validated_at, r.created_at, r.updated_at, r.extra,
  extract(year from r.tgl_permohonan)::int as tahun,
  d.nama as owner_nama,
  u.nama as unit_nama,
  (select string_agg(p.nama, '; ' order by p.urutan) from public.hki_persons p
    where p.record_id = r.id and p.peran = 'pencipta') as pencipta,
  (select string_agg(p.nama, '; ' order by p.urutan) from public.hki_persons p
    where p.record_id = r.id and p.peran = 'pemegang') as pemegang,
  (select min(coalesce(fv.confidence, 0)) from public.hki_field_values fv
    where fv.record_id = r.id and fv.field in ('judul', 'no_permohonan', 'tgl_permohonan', 'no_sertifikat')) as min_confidence
from public.hki_records r
left join public.dosen d on d.id = r.owner_dosen_id
left join public.units u on u.id = r.unit_id
where r.deleted_at is null;

grant select on public.hki_record_list to authenticated;
