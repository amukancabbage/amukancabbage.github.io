create or replace function public.hki_master_lock_key()
returns trigger language plpgsql set search_path = '' as $$
begin
  if new.nilai <> old.nilai or new.kategori <> old.kategori then
    raise exception 'MASTER_KEY_LOCKED: Nilai dan kategori master tidak boleh diubah; nonaktifkan lalu buat baru';
  end if;
  return new;
end;
$$;

drop trigger if exists hki_master_lock_key on public.hki_master_items;
create trigger hki_master_lock_key before update on public.hki_master_items
  for each row execute function public.hki_master_lock_key();

