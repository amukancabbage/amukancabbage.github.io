-- Artikel mahasiswa: penulis utama (npm & nama), anggota mahasiswa (jsonb), anggota dosen (tabel penghubung)

-- ============================================================
-- 1. Tabel
-- ============================================================
create table if not exists public.artikel_mahasiswa (
  id bigint generated by default as identity primary key,
  judul text not null,
  npm text,
  nama text not null,
  -- pilihan di aplikasi: conference/jurnal nasional/internasional (sengaja tanpa check agar mudah ditambah)
  jenis_artikel text not null,
  publisher text,
  -- daftar anggota mahasiswa: [{"npm": "2210010001", "nama": "..."}]
  anggota_mahasiswa jsonb not null default '[]'::jsonb,
  created_by uuid default auth.uid() references auth.users (id) on delete set null
);

create table if not exists public.artikel_mahasiswa_dosen (
  artikel_mahasiswa_id bigint not null references public.artikel_mahasiswa (id) on delete cascade,
  dosen_id bigint not null references public.dosen (id) on delete restrict,
  primary key (artikel_mahasiswa_id, dosen_id)
);

-- kolom yang ditambahkan setelah tabel dibuat; aman dijalankan ulang
alter table public.artikel_mahasiswa
  add column if not exists tahun smallint check (tahun between 1900 and 2100),
  add column if not exists url_bukti text,
  add column if not exists url_dokumen text;

create index if not exists artikel_mahasiswa_dosen_dosen_idx on public.artikel_mahasiswa_dosen (dosen_id);

-- ============================================================
-- 2. Fungsi bantu (lihat auth.sql untuk my_role, my_dosen_id, is_admin)
-- ============================================================
create or replace function public.is_dosen_artikel(aid bigint)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.artikel_mahasiswa_dosen
    where artikel_mahasiswa_id = aid and dosen_id = public.my_dosen_id()
  );
$$;

create or replace function public.is_pembuat_artikel(aid bigint)
returns boolean language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.artikel_mahasiswa
    where id = aid and created_by = auth.uid()
  );
$$;

-- ============================================================
-- 3. Hak akses (RLS)
--   lihat     : admin & pemantau semua; dosen sebagai anggota dosen atau penginput
--   tambah    : admin, atau dosen (tercatat sebagai penginput)
--   ubah/hapus: admin, anggota dosen, atau penginput
-- ============================================================
alter table public.artikel_mahasiswa enable row level security;
alter table public.artikel_mahasiswa_dosen enable row level security;

create policy "lihat artikel_mahasiswa" on public.artikel_mahasiswa
  for select to authenticated using (
    coalesce(public.my_role() in ('admin', 'pemantau'), false)
    or created_by = auth.uid()
    or public.is_dosen_artikel(id)
  );

create policy "tambah artikel_mahasiswa" on public.artikel_mahasiswa
  for insert to authenticated
  with check (
    public.is_admin()
    or (public.my_role() = 'dosen' and created_by = auth.uid())
  );

create policy "ubah artikel_mahasiswa" on public.artikel_mahasiswa
  for update to authenticated
  using (public.is_admin() or created_by = auth.uid() or public.is_dosen_artikel(id))
  with check (public.is_admin() or created_by = auth.uid() or public.is_dosen_artikel(id));

create policy "hapus artikel_mahasiswa" on public.artikel_mahasiswa
  for delete to authenticated
  using (public.is_admin() or created_by = auth.uid() or public.is_dosen_artikel(id));

create policy "lihat dosen artikel_mahasiswa" on public.artikel_mahasiswa_dosen
  for select to authenticated using (
    coalesce(public.my_role() in ('admin', 'pemantau'), false)
    or public.is_pembuat_artikel(artikel_mahasiswa_id)
    or public.is_dosen_artikel(artikel_mahasiswa_id)
  );

create policy "kelola dosen artikel_mahasiswa" on public.artikel_mahasiswa_dosen
  for all to authenticated
  using (
    public.is_admin()
    or public.is_pembuat_artikel(artikel_mahasiswa_id)
    or public.is_dosen_artikel(artikel_mahasiswa_id)
  )
  with check (
    public.is_admin()
    or public.is_pembuat_artikel(artikel_mahasiswa_id)
    or public.is_dosen_artikel(artikel_mahasiswa_id)
  );


