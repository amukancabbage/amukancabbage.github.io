-- HAKI fase 1: role baru (validator, operator), unit berhierarki, cakupan unit di profil.
-- Keputusan: docs/haki-migrasi/GAP-DAN-PEMETAAN.md (D2, D5, D6).

-- ============================================================
-- 1. Unit: universitas > fakultas > prodi
-- ============================================================
create table if not exists public.units (
  id bigint generated by default as identity primary key,
  nama text not null,
  tipe text not null default 'fakultas' check (tipe in ('universitas', 'fakultas', 'prodi')),
  parent_id bigint references public.units (id) on delete restrict
);

create unique index if not exists units_nama_uq on public.units (lower(nama));
create index if not exists units_parent_idx on public.units (parent_id);

-- siklus langsung maupun tidak langsung ditolak
create or replace function public.units_no_cycle()
returns trigger language plpgsql set search_path = '' as $$
declare
  cur bigint := new.parent_id;
  steps int := 0;
begin
  while cur is not null loop
    if cur = new.id then
      raise exception 'UNIT_CYCLE: Unit tidak boleh menjadi induk dari dirinya sendiri';
    end if;
    select parent_id into cur from public.units where id = cur;
    steps := steps + 1;
    exit when steps > 100;
  end loop;
  return new;
end;
$$;

drop trigger if exists units_no_cycle on public.units;
create trigger units_no_cycle before insert or update on public.units
  for each row execute function public.units_no_cycle();

-- unit p_unit termasuk cakupan p_scope (dirinya atau turunannya); p_scope null = seluruh institusi
create or replace function public.unit_in_scope(p_unit bigint, p_scope bigint)
returns boolean language sql stable security definer set search_path = '' as $$
  select p_scope is null or exists (
    with recursive up as (
      select id, parent_id from public.units where id = p_unit
      union
      select u.id, u.parent_id from public.units u join up on u.id = up.parent_id
    )
    select 1 from up where id = p_scope
  );
$$;

alter table public.prodi add column if not exists unit_id bigint references public.units (id) on delete set null;
alter table public.dosen add column if not exists unit_id bigint references public.units (id) on delete set null;
create index if not exists dosen_unit_idx on public.dosen (unit_id);

-- data awal: satu universitas, satu fakultas, satu unit per prodi
do $$
declare
  u bigint;
  f bigint;
  pu bigint;
  r record;
begin
  if not exists (select 1 from public.units) then
    insert into public.units (nama, tipe) values ('Universitas', 'universitas') returning id into u;
    insert into public.units (nama, tipe, parent_id)
      values ('Fakultas Teknologi Informasi', 'fakultas', u) returning id into f;
    for r in select id, prodi from public.prodi order by id loop
      insert into public.units (nama, tipe, parent_id) values (r.prodi, 'prodi', f) returning id into pu;
      update public.prodi set unit_id = pu where id = r.id;
    end loop;
    update public.dosen d set unit_id = p.unit_id
      from public.prodi p where p.id = d.prodi_id and d.unit_id is null;
  end if;
end;
$$;

-- prodi baru otomatis punya unit (di bawah fakultas pertama)
create or replace function public.prodi_ensure_unit()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  f bigint;
begin
  if new.unit_id is null then
    select id into f from public.units where tipe = 'fakultas' order by id limit 1;
    insert into public.units (nama, tipe, parent_id) values (new.prodi, 'prodi', f)
      on conflict ((lower(nama))) do nothing;
    select id into new.unit_id from public.units where lower(nama) = lower(new.prodi);
  end if;
  return new;
end;
$$;

drop trigger if exists prodi_ensure_unit on public.prodi;
create trigger prodi_ensure_unit before insert on public.prodi
  for each row execute function public.prodi_ensure_unit();

-- unit dosen mengikuti prodi-nya bila tidak diisi
create or replace function public.dosen_sync_unit()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if new.prodi_id is not null and (
    tg_op = 'INSERT' and new.unit_id is null
    or tg_op = 'UPDATE' and new.prodi_id is distinct from old.prodi_id and new.unit_id is not distinct from old.unit_id
  ) then
    select unit_id into new.unit_id from public.prodi where id = new.prodi_id;
  end if;
  return new;
end;
$$;

drop trigger if exists dosen_sync_unit on public.dosen;
create trigger dosen_sync_unit before insert or update on public.dosen
  for each row execute function public.dosen_sync_unit();

-- ============================================================
-- 2. Profil: role baru, cakupan unit, persetujuan privasi
-- ============================================================
alter table public.profiles drop constraint if exists profiles_role_check;
alter table public.profiles add constraint profiles_role_check
  check (role in ('admin', 'dosen', 'pemantau', 'validator', 'operator'));

alter table public.profiles
  add column if not exists unit_id bigint references public.units (id) on delete set null,
  add column if not exists privacy_notice_accepted_at timestamptz;

create or replace function public.my_unit_id()
returns bigint language sql stable security definer set search_path = '' as $$
  select unit_id from public.profiles where id = auth.uid();
$$;

-- operator wajib punya unit; admin terakhir tidak boleh diturunkan
create or replace function public.profiles_guard()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if new.role = 'operator' and new.unit_id is null then
    raise exception 'UNIT_REQUIRED: Operator wajib punya unit';
  end if;
  if tg_op = 'UPDATE' and old.role = 'admin' and new.role <> 'admin'
     and not exists (select 1 from public.profiles where role = 'admin' and id <> old.id) then
    raise exception 'LAST_ADMIN: Admin terakhir tidak boleh diubah perannya';
  end if;
  return new;
end;
$$;

drop trigger if exists profiles_guard on public.profiles;
create trigger profiles_guard before insert or update on public.profiles
  for each row execute function public.profiles_guard();

-- ============================================================
-- 3. Modul non-HAKI: validator & operator hanya membaca (seperti pemantau)
-- ============================================================
create or replace function public.is_reader()
returns boolean language sql stable security definer set search_path = '' as $$
  select coalesce(public.my_role() in ('admin', 'pemantau', 'validator', 'operator'), false);
$$;

create or replace function public.can_view_penelitian(pid bigint)
returns boolean language sql stable security definer set search_path = '' as $$
  select public.is_reader()
    or public.is_ketua(pid)
    or public.is_anggota(pid)
    or public.is_pembuat(pid);
$$;

drop policy if exists "lihat penelitian" on public.penelitian;
create policy "lihat penelitian" on public.penelitian
  for select to authenticated using (
    public.is_reader()
    or dosen_id = public.my_dosen_id()
    or created_by = auth.uid()
    or public.is_anggota(id)
  );

create or replace function public.can_view_pengabdian(pid bigint)
returns boolean language sql stable security definer set search_path = '' as $$
  select public.is_reader()
    or public.is_ketua_pengabdian(pid)
    or public.is_anggota_pengabdian(pid)
    or public.is_pembuat_pengabdian(pid);
$$;

drop policy if exists "lihat pengabdian" on public.pengabdian;
create policy "lihat pengabdian" on public.pengabdian
  for select to authenticated using (
    public.is_reader()
    or dosen_id = public.my_dosen_id()
    or created_by = auth.uid()
    or public.is_anggota_pengabdian(id)
  );

drop policy if exists "lihat artikel_mahasiswa" on public.artikel_mahasiswa;
create policy "lihat artikel_mahasiswa" on public.artikel_mahasiswa
  for select to authenticated using (
    public.is_reader()
    or created_by = auth.uid()
    or public.is_dosen_artikel(id)
  );

drop policy if exists "lihat dosen artikel_mahasiswa" on public.artikel_mahasiswa_dosen;
create policy "lihat dosen artikel_mahasiswa" on public.artikel_mahasiswa_dosen
  for select to authenticated using (
    public.is_reader()
    or public.is_pembuat_artikel(artikel_mahasiswa_id)
    or public.is_dosen_artikel(artikel_mahasiswa_id)
  );

-- ============================================================
-- 4. RLS unit: semua user login membaca, admin mengelola
-- ============================================================
alter table public.units enable row level security;

drop policy if exists "baca units" on public.units;
create policy "baca units" on public.units for select to authenticated using (true);

drop policy if exists "admin kelola units" on public.units;
create policy "admin kelola units" on public.units
  for all to authenticated using (public.is_admin()) with check (public.is_admin());
