-- Jalankan di Supabase Dashboard > SQL Editor (setelah schema.sql)

create table if not exists public.kategori_penelitian (
  id bigint generated by default as identity primary key,
  kategori_penelitian text not null
);

create table if not exists public.subkategori_penelitian (
  id bigint generated by default as identity primary key,
  sub_kategori_penelitian text not null,
  kategori_penelitian_id bigint not null
    references public.kategori_penelitian (id) on update cascade on delete restrict
);

create table if not exists public.penelitian (
  id bigint generated by default as identity primary key,
  dosen_id bigint not null
    references public.dosen (id) on update cascade on delete restrict,
  sub_kategori_penelitian_id bigint not null
    references public.subkategori_penelitian (id) on update cascade on delete restrict,
  judul_penelitian text not null,
  tahun smallint not null check (tahun between 1900 and 2100),
  publikasi text,
  url_bukti text,
  url_dokumen text,
  keterangan text
);

create index if not exists subkategori_penelitian_kategori_idx
  on public.subkategori_penelitian (kategori_penelitian_id);
create index if not exists penelitian_dosen_idx on public.penelitian (dosen_id);
create index if not exists penelitian_subkategori_idx
  on public.penelitian (sub_kategori_penelitian_id);

-- Row Level Security: izinkan akses publik dengan publishable/anon key.
-- Untuk produksi, batasi ke pengguna yang login (auth.role() = 'authenticated').
alter table public.kategori_penelitian enable row level security;
alter table public.subkategori_penelitian enable row level security;
alter table public.penelitian enable row level security;

create policy "akses publik kategori_penelitian" on public.kategori_penelitian
  for all using (true) with check (true);

create policy "akses publik subkategori_penelitian" on public.subkategori_penelitian
  for all using (true) with check (true);

create policy "akses publik penelitian" on public.penelitian
  for all using (true) with check (true);
